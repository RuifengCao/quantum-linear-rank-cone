# ------------------------------------------------------------------ 4. Lemma 1 on perturbed configurations
# Random perturbations of the configuration (6): up to three subgroups get an extra random vector, are replaced
# by a random vector, are multiplied by p (a smaller subgroup over Z_{p^a}), or are dropped.
# Over every ring the form whose hypothesis holds must never be violated, and the other form must be violated
# on some samples (which shows that the test has power).
def family_rank(fam, ring):
    n = len(fam)
    h = {0: 0.0}
    for m in range(1, 1 << n):
        cols = [v for i in range(n) if m >> i & 1 for v in fam[i]]
        h[m] = log_colspace(cols, ring) if cols else 0.0
    return h


def ideal_points(t):
    M = t + 1
    pts = [[1 if k == i else 0 for k in range(M)] for i in range(M)]
    pts += [[0 if k == i else 1 for k in range(M)] for i in range(M)]
    pts.append([1] * M)
    return pts                                    # A_1..A_M, B_1..B_M, C


def ring_order(ring):
    kind, q = ring
    return q if kind == 'p' else q[0] ** q[1]


def perturbed_family(t, ring, rng):
    """perturb between 0 and 3 randomly chosen subgroups of the configuration (6)."""
    M = t + 1
    Nr = ring_order(ring)
    dim = M + rng.choice([0, 0, 1])
    fam = [[v + [0] * (dim - M)] for v in ideal_points(t)]
    for i in rng.sample(range(2 * M + 1), rng.choice([0, 1, 1, 2, 2, 3])):
        v = fam[i][0]
        u = rng.random()
        if u < 0.4:
            fam[i] = [v, [rng.randrange(Nr) for _ in range(dim)]]
        elif u < 0.65:
            fam[i] = [[rng.randrange(Nr) for _ in range(dim)]]
        elif u < 0.85 and ring[0] == 'Z':
            fam[i] = [[(ring[1][0] * x) % Nr for x in v]]
        else:
            fam[i] = []
    return fam


def hypotheses(t, ring):
    """(LB) valid iff multiplication by t is injective; (LA) valid iff t kills the group."""
    kind, q = ring
    if kind == 'p':
        return t % q != 0, t % q == 0
    pp, a = q
    return t % pp != 0, t % (pp ** a) == 0


rng = random.Random(7)
cases = [(2, ('p', 2)), (2, ('p', 3)), (2, ('p', 5)), (3, ('p', 2)), (3, ('p', 3)),
         (2, ('Z', (3, 2))), (3, ('Z', (2, 2))), (4, ('Z', (2, 2)))]
for t, ring in cases:
    validB, validA = hypotheses(t, ring)
    trials = 120 if t <= 3 else 50
    mins = {'LB': math.inf, 'LA': math.inf}
    wrong_viol = 0
    for _ in range(trials):
        fam = perturbed_family(t, ring, rng)
        h = family_rank(fam, ring)
        LB, LA = lemma_forms(t, h, None)
        mins['LB'] = min(mins['LB'], LB)
        mins['LA'] = min(mins['LA'], LA)
        wrong_viol += (LB < -1e-9 and not validB) or (LA < -1e-9 and not validA)
    valid_ok = (not validB or mins['LB'] > -1e-9) and (not validA or mins['LA'] > -1e-9)
    name = ('GF(%d)' % ring[1]) if ring[0] == 'p' else ('Z_%d' % ring_order(ring))
    print('t = %d over %-6s: (LB) %s, min %.3f; (LA) %s, min %.3f; samples violating an invalid form: %d/%d'
          % (t, name, 'valid' if validB else 'not valid', mins['LB'], 'valid' if validA else 'not valid', mins['LA'],
             wrong_viol, trials))
    ok &= valid_ok and wrong_viol > 0
print('ALL OK' if ok else 'FAILURE')
