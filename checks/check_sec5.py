ok = True


def points(t):
    M = t + 1
    pts = []
    for i in range(M):
        pts.append([1 if k == i else 0 for k in range(M)])
    for i in range(M):
        pts.append([0 if k == i else 1 for k in range(M)])
    pts.append([1] * M)
    pts.append([0] * M)
    return [[1] + x for x in pts]          # columns (1, x)


def _vp(x, p):
    v = 0
    while x % p == 0:
        x //= p
        v += 1
    return v


def zn_invariants(rows, p, a):
    """valuations of the invariant factors of an integer matrix over Z_{p^a} (local ring elimination)."""
    N = p ** a
    M = [[x % N for x in r] for r in rows]
    vals = []
    while M and M[0]:
        best = None
        for i, r in enumerate(M):
            for j, x in enumerate(r):
                if x % N:
                    v = _vp(x, p)
                    if best is None or v < best[0]:
                        best = (v, i, j)
        if best is None:
            break
        v, i, j = best
        vals.append(v)
        piv = M[i][j]
        u = piv // (p ** v)
        uinv = pow(u, -1, N)
        # eliminate column j from other rows and row i from other columns
        newM = []
        for k, r in enumerate(M):
            if k == i:
                continue
            f = (r[j] // (p ** v)) * uinv % N
            newM.append([(r[c] - f * M[i][c]) % N for c in range(len(r)) if c != j])
        M = newM
    return vals


def log_colspace(cols, ring):
    """log2 of the order of the subgroup generated by the columns, over ring ('p', p) or ('Z', (p, a))."""
    if not cols:
        return 0.0
    kind, q = ring
    if kind == 'p':
        return rank_mod_p([list(c) for c in cols], q) * math.log2(q)
    pp, a = q
    vals = zn_invariants([list(c) for c in cols], pp, a)
    return sum((a - v) * math.log2(pp) for v in vals if v < a)


def rank_function(pts, ring):
    n = len(pts)
    r = {0: 0.0}
    for m in range(1, 1 << n):
        r[m] = log_colspace([pts[i] for i in range(n) if m >> i & 1], ring)
    return r


def lemma_forms(t, h, names):
    """values of (LB) and (LA) (right side minus left side, so >= 0 when valid) for a rank function h on masks
    over the 2M+1 elements A_1..A_M, B_1..B_M, C (bits 0..2M)."""
    M = t + 1
    A = [1 << i for i in range(M)]
    B = [1 << (M + i) for i in range(M)]
    Cc = 1 << (2 * M)
    allA = sum(A)
    H = lambda m: h[m]
    Hc = lambda x, y: H(x | y) - H(y)
    I = lambda x, y, z=0: H(x | z) + H(y | z) - H(x | y | z) - H(z)
    alpha = sum(H(a) for a in A) - H(allA)
    gamma = Hc(Cc, allA)
    delta = [I(Cc, allA ^ A[i]) for i in range(M)]
    eps = [Hc(Cc, A[i] | B[i]) for i in range(M)]
    zeta = [Hc(B[i], allA ^ A[i]) for i in range(M)]
    eta = [Hc(B[i], A[i] | Cc) for i in range(M)]
    HB = H(sum(B))
    LB = HB + M * (gamma + M * alpha + sum(delta) + sum(eps) + sum(zeta)) - M * H(Cc)
    LA = (M - 1) * H(Cc) + M * alpha + M * gamma + sum(zeta) + sum(eta) - HB
    return LB, LA


def contraction(h, n, o):
    """contraction of a rank function on n elements by element o: T -> h(T u o) - h(o), on the other elements
    (re-indexed in order)."""
    others = [i for i in range(n) if i != o]
    out = {}
    for m in range(1 << len(others)):
        M_ = sum(1 << others[k] for k in range(len(others)) if m >> k & 1)
        out[m] = h[M_ | 1 << o] - h[1 << o]
    return out


def self_dual(r, n):
    full = (1 << n) - 1
    for m in range(1 << n):
        rs = sum(r[1 << i] for i in range(n) if m >> i & 1) + r[full ^ m] - r[full]
        if abs(rs - r[m]) > 1e-9:
            return False
    return True


# ------------------------------------------------------------------ 1. witnesses of Theorem 4 (t = p)
for (t, fields) in [(2, [2, 3, 5]), (3, [3, 5, 7]), (5, [5, 7])]:
    pts = points(t)
    n = len(pts)
    O = n - 1
    vals = {}
    for p in fields:
        r = rank_function(pts, ('p', p))
        sd = self_dual(r, n)
        # S = lambda(r) in bits; h_S = 2 r (check through S)
        full = (1 << n) - 1
        S = {m: r[m] + r[full ^ m] - r[full] for m in range(1 << n)}
        hS = {m: S[m] + sum(S[1 << i] for i in range(n) if m >> i & 1) for m in range(1 << n)}
        h2r = all(abs(hS[m] - 2 * r[m]) < 1e-9 for m in range(1 << n))
        con = contraction(hS, n, O)
        LB, LA = lemma_forms(t, con, None)
        u = math.log2(p)
        vals[p] = (round(LB / u, 9), round(LA / u, 9), sd, h2r)
        # validity: (LB)_t valid if p does not divide t, (LA)_t if p divides t; the witness must violate the other
        if t % p == 0:
            ok &= sd and h2r and abs(LB / u + 2) < 1e-9 and LA >= -1e-9
        else:
            ok &= sd and h2r and abs(LA / u + 2) < 1e-9 and LB >= -1e-9
    print('t = %d: (LB, LA) on the pulled-back contraction, units of log p, self-dual, h_S = 2r:' % t, vals)

# ------------------------------------------------------------------ 2. one cut (Proposition 2)
for t in range(2, 6):
    pts = points(t)
    n = len(pts)
    M = t + 1
    rq = {}
    for m in range(1, 1 << n):
        rq[m] = rank_Q([pts[i] for i in range(n) if m >> i & 1])
    for ell in [2, 3, 5, 7, 11, 13]:
        if (t - 1) % ell == 0:
            continue
        pred_ok = True
        for m in range(1, 1 << n):
            rf = rank_mod_p([pts[i] for i in range(n) if m >> i & 1], ell)
            # predicted drop
            balanced = all(((m >> j & 1) + (m >> (M + j) & 1)) == 1 for j in range(M))
            a = sum(m >> (M + j) & 1 for j in range(M))
            cin, oin = m >> (2 * M) & 1, m >> (2 * M + 1) & 1
            drop = balanced and ((cin and not oin and (t - a) % ell == 0 and a != t) or
                                 (oin and not cin and (a - 1) % ell == 0 and a != 1))
            if rf != rq[m] - (1 if drop else 0):
                pred_ok = False
                break
        ok &= pred_ok
        if not pred_ok:
            print('one-cut prediction FAILS for t=%d ell=%d' % (t, ell))
print('Proposition 2 (one cut) checked for t = 2..5 and primes ell <= 13 with ell not dividing t-1')

# single cut for ell = t prime
for t in [2, 3, 5]:
    pts = points(t)
    n = len(pts)
    M = t + 1
    full = (1 << n) - 1
    cuts = set()
    for m in range(1, full):
        rq_m = rank_Q([pts[i] for i in range(n) if m >> i & 1])
