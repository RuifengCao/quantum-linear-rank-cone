def css_entropy(code_rows, owner, nsys, N):
    """entropy vector (log2) of the CSS state of the code spanned by code_rows over Z_N, coordinates owned by
    systems 0..nsys-1: S(X) = r(X) + r(complement) - r(all), r(X) = log2 |projection to X| (Supplementary Lemma 1.5).
    Returned as a function on frozensets of systems, with exact integer orders."""
    D = len(code_rows[0])
    k = len(code_rows)

    def proj_order(X):
        cols = [c for c in range(D) if owner[c] in X]
        if not cols:
            return 1
        # projection to the coordinates cols of the row space = column space of the transposed submatrix
        gens = [[code_rows[r][c] for c in cols] for r in range(k)]
        return order(gens, len(cols), N)

    allS = frozenset(range(nsys))
    tot = proj_order(allS)

    def S_order(X):
        X = frozenset(X)
        return Fraction(proj_order(X) * proj_order(allS - X), tot)
    return S_order


def doubled_code_T(M, N):
    """rows of [G | G] with G = [I | J - I] (M x 2M); systems 0..2M-1 own the first copy, system 2M the second."""
    G = [[1 if k == i else 0 for k in range(M)] + [0 if k == i else 1 for k in range(M)] for i in range(M)]
    rows = [r + r for r in G]
    owner = list(range(2 * M)) + [2 * M] * (2 * M)
    return rows, owner


