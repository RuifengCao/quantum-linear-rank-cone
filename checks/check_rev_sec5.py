# ------------------------------------------------------------------- (3) the proof, step by step, over GF(p)
def span_basis(vecs, p):
    """reduced row echelon basis of the span of vecs over GF(p)."""
    rows = [[x % p for x in v] for v in vecs]
    basis = []
    for v in rows:
        for b in basis:
            piv = next(i for i, x in enumerate(b) if x)
            if v[piv]:
                f = v[piv]
                v = [(a - f * c) % p for a, c in zip(v, b)]
        if any(v):
            piv = next(i for i, x in enumerate(v) if x)
            inv = pow(v[piv], p - 2, p)
            v = [(x * inv) % p for x in v]
            nb = []
            for b in basis:
                if b[piv]:
                    f = b[piv]
                    b = [(a - f * c) % p for a, c in zip(b, v)]
                nb.append(b)
            basis = nb + [v]
    return basis


def intersect(X, Y, p, D):
    """basis of span(X) cap span(Y) over GF(p)."""
    X, Y = span_basis(X, p), span_basis(Y, p)
    if not X or not Y:
        return []
    # solve sum a_i x_i = sum b_j y_j: kernel of the matrix with columns x_i and -y_j
    cols = X + [[(-c) % p for c in y] for y in Y]
    n = len(cols)
    # rows of the system: D equations
    mat = [[cols[k][r] for k in range(n)] for r in range(D)]
    # nullspace over GF(p)
    m = [row[:] for row in mat]
    pivcols, r = [], 0
    for c in range(n):
        piv = next((i for i in range(r, D) if m[i][c] % p), None)
        if piv is None:
            continue
        m[r], m[piv] = m[piv], m[r]
        inv = pow(m[r][c], p - 2, p)
        m[r] = [(x * inv) % p for x in m[r]]
        for i in range(D):
            if i != r and m[i][c]:
                f = m[i][c]
                m[i] = [(a - f * b) % p for a, b in zip(m[i], m[r])]
        pivcols.append(c)
        r += 1
    free = [c for c in range(n) if c not in pivcols]
    out = []
    for fc in free:
        sol = [0] * n
        sol[fc] = 1
        for i, pc in enumerate(pivcols):
            sol[pc] = (-m[i][fc]) % p
        vec = [sum(sol[k] * X[k][d] for k in range(len(X))) % p for d in range(D)]
        out.append(vec)
    return span_basis(out, p)


def dim(vecs, p):
    return len(span_basis(vecs, p))


