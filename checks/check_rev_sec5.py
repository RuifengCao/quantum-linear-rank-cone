# ----------------------------------------------------------------------------------------------- group orders
def egcd(a, b):
    if b == 0:
        return (abs(a), 1 if a >= 0 else -1, 0)
    g, x, y = egcd(b, a % b)
    return (g, y, x - (a // b) * y)


def lattice_index(gens, D, N):
    """[Z^D : L] for the lattice L spanned by the integer vectors gens and N Z^D (row echelon form over Z)."""
    basis = [None] * D
    rows = [list(v) for v in gens] + [[N if i == j else 0 for j in range(D)] for i in range(D)]
    for r in rows:
        r = list(r)
        for i in range(D):
            if r[i] == 0:
                continue
            if basis[i] is None:
                if r[i] < 0:
                    r = [-x for x in r]
                basis[i] = r
                break
            b = basis[i]
            g, x, y = egcd(b[i], r[i])
            nb = [x * bb + y * rr for bb, rr in zip(b, r)]
            nr = [(r[i] // g) * bb - (b[i] // g) * rr for bb, rr in zip(b, r)]
            # entries to the right of the pivot may be reduced modulo N, since N e_j lies in L
            basis[i] = nb[:i + 1] + [x % N for x in nb[i + 1:]]
            r = nr[:i + 1] + [x % N for x in nr[i + 1:]]
    idx = 1
    for i in range(D):
        assert basis[i] is not None
        idx *= abs(basis[i][i])
    return idx


def order(gens, D, N):
    """order of the subgroup of Z_N^D generated by gens."""
    return N ** D // lattice_index(gens, D, N)


class Arrangement:
    """subgroups U_0..U_{k-1} of Z_N^D; h(X) as the exact order of the sum (X a set of indices)."""

    def __init__(self, subgroups, D, N):
        self.U, self.D, self.N = subgroups, D, N
        self.cache = {}

    def order(self, X):
        X = frozenset(X)
        if X not in self.cache:
            gens = [v for i in X for v in self.U[i]]
            self.cache[X] = order(gens, self.D, self.N) if gens else 1
        return self.cache[X]


class Form:
    """integer linear combination of terms h(X); value(arr) = 2^(form) as an exact Fraction."""

    def __init__(self):
        self.c = {}

    def add(self, X, coeff):
        X = frozenset(X)
        self.c[X] = self.c.get(X, 0) + coeff
        if self.c[X] == 0:
            del self.c[X]
        return self

    def addform(self, other, mult=1):
        for X, v in other.c.items():
            self.add(X, mult * v)
        return self

    def value(self, arr):
        num, den = 1, 1
        for X, v in self.c.items():
            o = arr.order(X) if X else 1
            if v > 0:
                num *= o ** v
            else:
                den *= o ** (-v)
        return Fraction(num, den)

    def on_setfunction(self, f):
        """value on a set function given as a Python function of frozensets (real numbers)."""
        return sum(v * f(X) for X, v in self.c.items())


def h(*sets):
    F = Form()
    F.add(frozenset().union(*[frozenset(s) for s in sets]), 1)
    return F


def cond(X, Y):          # h(X | Y)
    return Form().add(set(X) | set(Y), 1).add(Y, -1)


def mi(X, Y, Z=()):      # I(X; Y | Z)
    X, Y, Z = set(X), set(Y), set(Z)
    return Form().add(X | Z, 1).add(Y | Z, 1).add(X | Y | Z, -1).add(Z, -1)


def lemma2_forms(M, jmap):
    """the forms (LB*) and (LA*) of Supplementary Lemma 4.1 as right-hand side minus left-hand side (>= 0 when valid)."""
    A = list(range(M))
    B = list(range(M, 2 * M))
    P = lambda m: {A[m], B[m]}

    def p(*ms):
        return set().union(*[P(m) for m in ms])

    L = Form().add(p(0), 1).add(p(1), 1).add(p(0, 1), -1)
    for k in range(2, M):
        L.add(p(k), 1).add(p(0, k), -1).add(p(1, k), -1).add(p(0, 1, k), 1)
    Aall = set(A)
    alpha = Form()
    for k in A:
        alpha.add({k}, 1)
    alpha.add(Aall, -1)
    kappa = Form().add(set(A) | set(B), 1).add(Aall, -1)
    zeta = [cond({B[i]}, Aall - {A[i]}) for i in range(M)]
    dstar = [Form().addform(mi(p(jmap[i]), {B[i]})).addform(mi({A[i]}, Aall - {A[i]}, {B[i]})) for i in range(M)]
    theta = [mi({A[i]}, p(jmap[i])) for i in range(M)]
    hB = Form().add(set(B), 1)
    LB = Form().addform(hB)
    LB.addform(kappa, M).addform(alpha, M * M)
    for i in range(M):
        LB.addform(dstar[i], M).addform(zeta[i], M)
    LB.addform(L, -M)
    LA = Form()
    for i in range(M):
        LA.add(p(i), 1).add({A[i]}, -1)
        LA.addform(theta[i]).addform(zeta[i])
    LA.addform(L, -1).addform(alpha, M).addform(kappa, M).addform(hB, -1)
    return LB, LA, L


